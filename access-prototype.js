const outcomes = {
  allowed: ["Report opens", "After GitHub sign-in and a current team check, the proxy privately redirects an active member to Antithesis. No report URL is generated by this preview."],
  denied: ["Access denied", "The proxy refuses to disclose the report URL when active pragma-org/antithesis-access membership cannot be established. Public browsing remains available."],
  pending: ["Report not ready", "The test is still starting or running. Return to the dashboard and open the report again when it finishes."],
  missing: ["Report unavailable", "This run has no report available. Public run details and the dashboard remain available."],
  failure: ["Please try again", "A cancelled sign-in or unavailable service discloses no report URL. Open the report again or use the proxy account page to sign out before retrying."]
};
document.getElementById("access-state").addEventListener("change", event => {
  const [title, text] = outcomes[event.target.value];
  document.getElementById("outcome-title").textContent = title;
  document.getElementById("outcome-text").textContent = text;
});
